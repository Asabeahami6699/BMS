export function getNavIcon(label: string, path?: string): string {
  if (path) {
    const key = path.replace(/^\/+/, "").replace(/^app\//, "");
    if (iconByPath[key]) {
      return iconByPath[key];
    }
  }
  return iconByLabel[label] ?? "•";
}
